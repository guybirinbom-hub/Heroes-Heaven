/**
 * The card's scope rules — what a 'mine' card may leave out of, or fold inside, a record's page
 * (docs/card-design.md sections 2 rule 5 and 3; owner rulings in section 13).
 *
 * Card step 4: a PURE STUB. It names the rules and the one switch, and folds nothing: no surface folds
 * yet, so `foldsOf` returns no folds and scripts/card-truth-check.mjs's FOLDED-UNLISTED section reads 0
 * by measurement, not by assumption. Step 13 fills `foldsOf` from scripts/data/level-folds.json; the
 * guard already imports it, so the day a fold appears the check sees it.
 *
 * Card step 5 adds the printed set (the label table, canonLabel, printedSet): the 'mine' card and the
 * guard both read it from here. The tree predicates that use it live in astVisibility.ts.
 *
 * Card step 13a adds the LEVEL FOLDS (section 3; owner ruling Q1 = A): `scopeTree` folds the sections
 * of a page the character does not have yet, reading ONLY the reviewed ledger
 * scripts/data/level-folds.json (generated by scripts/level-folds.mjs, checked both ways by
 * scripts/level-folds-check.mjs) — never a regex at run time. `foldsOf` now reports the folds a 'mine'
 * row draws at the guard's scope grid, so FOLDED-UNLISTED measures them.
 *
 * Card step 13c adds the CHOOSE-ONE BLOCKS (section 3; owner ruling Q2 = A): where a record's page
 * prints its options as separate bold-led blocks and the row's pick names exactly one of them, the
 * picked option stays open and highlighted and the other options fold under ONE "Other options (k)"
 * line whose k counts OPTIONS. A pick that matches no printed option (or a block that groups several
 * options under one label, dragon-disciple-dedication) folds nothing: the whole text stays open. An
 * "Other options" line always counts options now, the ledger's gated sections included.
 *
 * Card step 13b adds the PROSE GATES (section 3 row "Paragraph that OPENS with 'At Nth level,'"): a
 * top-level paragraph the ledger lists under `prose` (generated by scripts/level-folds.mjs after a seeded
 * 60-record hand check on the trees) folds WHOLE, through the same fold as a level section, while the
 * character is below its level — matched by the paragraph's hash, so a changed page folds nothing.
 *
 * A plain .ts file with no JSX and no stylesheet, because the guard imports it through jiti.
 */
