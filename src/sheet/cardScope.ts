/**
 * The ledger's shape (scripts/data/level-folds.json, written by scripts/level-folds.mjs):
 *  - pages: page key "bucket:slug" → its LEVEL-TITLED sections — a level-2/3 title at the top of the
 *    page whose right badge reads "Level N" or "Nth" — each with its index in the stored tree, title,
 *    level, the hash of the section's text and, for an option page whose sections the build owns or
 *    not (thaumaturge implement, kineticist element, inventor innovation), the ownership gate.
 *  - impulses: page key → the kineticist impulse's "Level (+N)" / "Level (Nth)" paragraphs.
 *  - pointers: a class-feature row that only points at the subclass text ("listed in your cause") →
 *    the subclass section it shows (title = the row's name).
 *  - subclassPages: "classId:subclassId" → the subclass's page key.
 * The runtime matches a section by its HASH, so a page whose text changed (a regen) folds nothing
 * until the ledger is regenerated and reviewed — scripts/level-folds-check.mjs turns red first.
 */
export type FoldGate =
  | { kind: 'implement'; option: string; tier: 'adept' | 'intensify' | 'paragon' }
  | { kind: 'element'; option: string; junction?: 'single' }
  | { kind: 'innovation'; option: string };
export interface FoldSection { i: number; title: string; level: number; hash: string; gate?: FoldGate }
export interface ImpulseEntry { i: number; hash: string; featLevel: number; plus?: number; at?: number }
/** Card step 13b: a prose gate — the top-level paragraph at `i` opens with a level gate ("At 8th level,
 *  …", "When you reach 15th level, …", "If you're at least 10th level, …") and folds whole below `level`.
 *  `fam` names the gate family the generator read (for review; the card reads only i / level / hash). */
export interface ProseGate { i: number; level: number; hash: string; fam?: string }
export interface LevelFoldLedger {
  _about?: string;
  pages: Record<string, FoldSection[]>;
  impulses: Record<string, ImpulseEntry[]>;
  pointers: Record<string, { classId: string; title: string; level: number }>;
  subclassPages: Record<string, string>;
  prose?: Record<string, ProseGate[]>;
}
/** The shipped ledger — the same file the card renders with and the guard measures with. */
export const LEVEL_FOLDS = LEVEL_FOLDS_JSON as unknown as LevelFoldLedger;

/** Why a run of sections is folded: a later level ('future', S-future) or an option the build does
 *  not have ('pick', S-pick, owner ruling Q2 = A: "Other options (k)"). */
export type FoldReason = 'future' | 'pick';
export const FOLD_LABEL: Record<FoldReason, string> = { future: 'At higher levels', pick: 'Other options' };
export const FOLD_RULE: Record<FoldReason, OmissionRule> = { future: 'S-future', pick: 'S-pick' };

/** A node scopeTree adds or marks. `card-fold` wraps a folded run; `card-pointer` wraps a subclass
 *  section a pointer row shows; `applies` marks an impulse "Level" paragraph that applies, and the
 *  picked option's paragraph of a choose-one block (card step 13c). */
export interface ScopedNode extends AstNode {
  foldReason?: FoldReason;
  treatment?: FutureTreatment;
  /**
   * What the fold's line counts, one id each (AstRenderer draws "<label> (foldIds.length)"):
   *  - 'future': the ledger ids ("bucket:slug#i") of the sections inside — "At higher levels (2)";
   *  - 'pick': the OPTIONS inside — a gated ledger run's option ("implement:bell"), or a choose-one
   *    block's option ("<record>#<block>.<option>") — so "Other options (k)" counts options, never the
   *    sections of one option (card step 13c).
   */
  foldIds?: string[];
  /** The ledger ids ("bucket:slug#i") of the sections inside a fold (any reason). */
  sectionIds?: string[];
  /** A choose-one fold: the printed labels of the options inside it (card step 13c). */
  options?: string[];
  /** The page key a card-pointer's section comes from. */
  pointerFrom?: string;
  applies?: boolean;
  /** Card step 13c: the picked option of a choose-one block (the list item or paragraph) and the list
   *  holding it. Its own paragraph carries `applies`, the highlight the renderer draws. */
  picked?: boolean;
}

/** Raw text of a node (no hygiene: the hash only needs to be deterministic). */
export function foldText(n: AstNode | undefined): string {
  if (!n) return '';
  if (n.t === 'text') return n.v ?? '';
  return (n.c ?? []).map(foldText).join('');
}
/** FNV-1a, 32 bits, as 8 hex digits — the same in the browser, jiti and node. */
export function foldHash(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}
const squashAll = (s: string) => s.replace(/\s+/g, '');
const optionSlug = (s: string) => s.toLowerCase().normalize('NFKD').replace(/[’']/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/** A title badge → its level: "Level 9" → 9, "7th" → 7; anything else → null. */
export function levelOfRight(right: unknown): number | null {
  const r = String(right ?? '').trim();
  const m = /^(?:Level|Lv\.?)\s*(\d{1,2})$/i.exec(r) ?? /^(\d{1,2})(?:st|nd|rd|th)$/i.exec(r);
  return m ? Number(m[1]) : null;
}
/** A level-2/3 title with a level badge: the start of a level-titled section. */
export function isLevelTitle(n: AstNode | undefined): boolean {
  if (!n || n.t !== 'title') return false;
  const lv = Number(n.level ?? 1);
  return lv >= 2 && lv <= 3 && levelOfRight(n.right) !== null;
}
/**
 * Where the section opened by the title at top[j] ends: the NEXT TITLE OF ANY RANK. A level section owns
 * only the words under its own title. Ending at "the same or a higher rank" let archetype:spellshot's
 * level-2 "Greater Deed" (15th) run over the level-3 "Additional Feats" rule and all 11 archetype feats to
 * the end of the page, folding them as later-level text (refuter, 2026-10-03). Measured on the shipped
 * trees: no other level section of the 972 holds an inner title, so no other hash moves; a badge-less
 * sub-heading that did belong would end the fold early — text shown, never text hidden.
 */
export function sectionEnd(top: AstNode[], j: number): number {
  let k = j + 1;
  while (k < top.length && top[k].t !== 'title') k++;
  return k;
}
/** The page's own title (its level-1 title), part of every hash so two pages' identical words differ. */
export function pageTitleOf(top: AstNode[]): string {
  const t = top.find((n) => n.t === 'title' && Number(n.level ?? 1) <= 1);
  return squashAll(foldText(t));
}
/** The hash of the section opened at top[j]: page title, badge and every node of the section. */
export function sectionHash(top: AstNode[], j: number): string {
  const end = sectionEnd(top, j);
  return foldHash(`${pageTitleOf(top)}|${String(top[j].right ?? '').trim()}|${top.slice(j, end).map((n) => squashAll(foldText(n))).join('|')}`);
}
/** The hash of one top-level paragraph (an impulse "Level" entry). */
export function paragraphHash(top: AstNode[], j: number): string {
  return foldHash(`${pageTitleOf(top)}|${squashAll(foldText(top[j]))}`);
}

interface LedgerIndex {
  sections: Map<string, { key: string; entry: FoldSection }>;
  impulses: Map<string, { key: string; entry: ImpulseEntry }>;
  /** Card step 13b: paragraph hash → page key → gate. Keyed by BOTH: two pages that print the same
   *  paragraph under the same title (actions:furious-strike and its classFeatures copy, the implement
   *  pages and their classFeatures benefit copies) share a hash, and a fold must name its own page. */
  prose: Map<string, Map<string, ProseGate>>;
}
const INDEXES = new WeakMap<LevelFoldLedger, LedgerIndex>();
function indexOf(ledger: LevelFoldLedger): LedgerIndex {
  let ix = INDEXES.get(ledger);
  if (!ix) {
    ix = { sections: new Map(), impulses: new Map(), prose: new Map() };
    for (const [key, list] of Object.entries(ledger.pages ?? {})) for (const entry of list) ix.sections.set(entry.hash, { key, entry });
    for (const [key, list] of Object.entries(ledger.impulses ?? {})) for (const entry of list) ix.impulses.set(entry.hash, { key, entry });
    for (const [key, list] of Object.entries(ledger.prose ?? {})) {
      for (const entry of list) {
        let byPage = ix.prose.get(entry.hash);
        if (!byPage) ix.prose.set(entry.hash, (byPage = new Map()));
        byPage.set(key, entry);
      }
    }
    INDEXES.set(ledger, ix);
  }
  return ix;
}
/** The page key a tree's own level-1 title links to ("actions:furious-strike" — the Archives page the
 *  tree IS, whichever bucket holds a copy of it), or undefined. */
export function pageRefOf(top: readonly AstNode[]): string | undefined {
  const title = top.find((n) => n.t === 'title' && Number(n.level ?? 1) <= 1);
  let ref: string | undefined;
  (function walk(n: AstNode | undefined) {
    if (!n || ref) return;
    if (typeof n.ref === 'string' && n.ref) { ref = n.ref; return; }
    for (const c of n.c ?? []) walk(c);
  })(title);
  return ref;
}
/**
 * Card step 13b: the ledger's prose gate for one paragraph hash ON ONE PAGE. The page is the record the
 * card opened (`own`) when the ledger lists the hash under it, else the page the tree's own title links to
 * (pageRefOf), else the one page that lists the hash. A hash several pages list and neither names (the
 * thaumaturge's adept/initiate/paragon-benefit-weapon copies of implement-9, whose title link has no ref)
 * folds only when every one of those pages lists it at the same paragraph and level — identical pages —
 * and the fold names them all ("a|b|c#5"), never one of them by guess; otherwise the paragraph stays open.
 */
function proseGateAt(ix: LedgerIndex, hash: string, pages: readonly (string | undefined)[]): { key: string; entry: ProseGate } | undefined {
  const byPage = ix.prose.get(hash);
  if (!byPage) return undefined;
  for (const k of pages) {
    const entry = k ? byPage.get(k) : undefined;
    if (entry) return { key: k!, entry };
  }
  const all = [...byPage];
  const [, first] = all[0];
  if (all.some(([, e]) => e.i !== first.i || e.level !== first.level)) return undefined;
  return { key: all.map(([k]) => k).join('|'), entry: first };
}
/** Is this section hash in the ledger? (the guard's FOLDED-UNLISTED test) */
export function ledgerHasSection(hash: string, ledger: LevelFoldLedger = LEVEL_FOLDS): boolean {
  return indexOf(ledger).sections.has(hash);
}
/** Card step 13b: is this paragraph hash a prose gate of the ledger — on page `key` when one is given, on
 *  any page otherwise? (FOLDED-UNLISTED for a paragraph) */
export function ledgerHasProse(hash: string, ledger: LevelFoldLedger = LEVEL_FOLDS, key?: string): boolean {
  const byPage = indexOf(ledger).prose.get(hash);
  return !!byPage && (key === undefined || byPage.has(key));
}
/** Card step 13b: a prose gate's verdict — folded ('future') while the character is below its level. */
export function proseVerdict(entry: ProseGate, scope: CardScope): 'open' | FoldReason {
  return scope.level >= entry.level ? 'open' : 'future';
}

/**
 * One ledger section's verdict at a scope: 'open', or the reason it folds.
 *  - No gate: the level rule (folded while the section's level is above the character's).
 *  - implement: an implement the build does not have → 'pick'; its adept / paragon benefit folds until
 *    the build grants it (build.ts pushBenefit: adept at 7 / 11, Intense Implement, paragon at 17) —
 *    level alone would show it to every thaumaturge of that level; intensify follows the level rule.
 *  - element: an element the build does not channel → 'pick'; the single-gate impulse junction belongs
 *    to a single gate's element — any other element's (a dual gate, a forked element) can be had only
 *    as a gate junction from level 5, which the build does not record, so below 5 it is 'pick' and from
 *    5 it is shown (unmapped, never guessed).
 *  - innovation: another innovation than the build's → 'pick'.
 * An ownership set absent from the scope is UNKNOWN: the section follows the level rule alone.
 */
export function sectionVerdict(entry: FoldSection, scope: CardScope): 'open' | FoldReason {
  const byLevel: 'open' | FoldReason = scope.level >= entry.level ? 'open' : 'future';
  const g = entry.gate;
  if (!g) return byLevel;
  if (g.kind === 'implement') {
    const imp = scope.implements;
    if (!imp) return byLevel;
    if (!imp.owned.includes(g.option)) return 'pick';
    if (g.tier === 'adept') return imp.adept.includes(g.option) ? byLevel : 'future';
    if (g.tier === 'paragon') return imp.paragon.includes(g.option) ? byLevel : 'future';
    return byLevel;
  }
  if (g.kind === 'element') {
    const el = scope.elements;
    if (!el) return byLevel;
    if (!el.owned.includes(g.option)) return 'pick';
    if (g.junction === 'single' && el.single !== g.option && scope.level < 5) return 'pick';
    return byLevel;
  }
  if (g.kind === 'innovation') {
    if (!scope.innovation) return byLevel;
    return scope.innovation === g.option ? byLevel : 'pick';
  }
  return byLevel;
}

/** Does an impulse "Level" entry apply at this character level? "(+N)" counts up from the feat's own
 *  level (it applies once the character is N levels past it); "(Nth)" applies from level N. */
export function impulseApplies(entry: ImpulseEntry, level: number): boolean {
  if (entry.plus != null) return level >= entry.featLevel + entry.plus;
  if (entry.at != null) return level >= entry.at;
  return false;
}

/** The option a gated ledger section belongs to ("implement:bell"), or the section's own id: what an
 *  "Other options (k)" line counts for a run of ledger sections (card step 13c). */
function gateOptionId(entry: FoldSection, sectionId: string): string {
  return entry.gate ? `${entry.gate.kind}:${entry.gate.option}` : sectionId;
}
/** The fold node of a run: 'future' counts its sections, 'pick' the distinct options among them. */
function runFold(reason: FoldReason, nodes: AstNode[], ids: string[], options: string[], treatment: FutureTreatment): ScopedNode {
  return { t: 'card-fold', c: nodes, foldReason: reason, treatment, foldIds: reason === 'pick' ? [...new Set(options)] : ids, sectionIds: ids };
}

/**
 * Scope a page tree for a 'mine' card. Every ledger section whose verdict is not 'open' is moved, with
 * its title and text, into a `card-fold` node — consecutive folded sections with the same reason share
 * ONE fold, so a Justice champion at 5 sees one "At higher levels (2)" line. Nothing is deleted: the
 * fold carries the treatment and the renderer decides (fold: a closed <details> whose text stays in the
 * DOM; hide: a marker element only; grey: in place, dimmed). Impulse "Level" entries that apply are
 * marked `applies` (a highlight; nothing is hidden). No scope (browse, search, the builder's pickers)
 * returns the tree itself. Card step 13b: a ledger prose gate (`prose`, matched by paragraphHash) below
 * the character's level is moved into the same run, whole — "At higher levels (k)" counts sections and
 * prose gates alike; a paragraph whose words changed hashes differently and stays open.
 *
 * Card step 13c: `own` ("bucket:id", the record the card opened) names the record whose pick
 * (scope.picks[own]) scopes the page's choose-one blocks — see scopeChoiceBlock. A classFeatures page
 * with no pick of its own is scoped by the character's class picks (classPicksOf: the subclass and the
 * divine font, and the gate's elements on ELEMENT_PICK_PAGES only — scopeOfCharacter). Without `own`, or with no pick
 * for it, no choose-one block is touched. Nor is a block inside a ledger section: such a
 * block can be a LATER question than the row's pick (initiate-benefit-wand's Adept Benefit asks for "a
 * second" damage type from the same three), so matching it would highlight the wrong option.
 */
export function scopeTree(tree: AstNode, scope: CardScope | undefined, ledger: LevelFoldLedger = LEVEL_FOLDS, treatment: FutureTreatment = FUTURE_TREATMENT, own?: string): AstNode {
  if (!scope) return tree;
  const ix = indexOf(ledger);
  const top = tree.c ?? [];
  const out: AstNode[] = [];
  let run: { reason: FoldReason; nodes: AstNode[]; ids: string[]; options: string[] } | null = null;
  let changed = false;
  const flush = () => {
    if (!run) return;
    out.push(runFold(run.reason, run.nodes, run.ids, run.options, treatment));
    run = null;
    changed = true;
  };
  // Card step 13c: the choose-one blocks the row's pick scopes, by the index they start at. The row's own
  // pick wins; a classFeatures page without one is scoped by the character's class picks (CLASS_PICKS).
  const rowPick = own ? scope.picks?.[own] : undefined;
  const pick: readonly string[] = rowPick ? pickCandidates(rowPick) : own?.startsWith(CLASS_PICK_BUCKET) ? classPicksOf(scope, own) : [];
  const blocks = new Map<number, ChoiceBlock>();
  if (pick.length) for (const b of choiceBlocksOf(top)) blocks.set(b.start, b);
  let titleRef: string | undefined;
  for (let j = 0; j < top.length; j++) {
    const n = top[j];
    if (isLevelTitle(n)) {
      const hit = ix.sections.get(sectionHash(top, j));
      if (hit) {
        const end = sectionEnd(top, j);
        const v = sectionVerdict(hit.entry, scope);
        if (v === 'open') {
          flush();
          out.push(...top.slice(j, end));
        } else {
          if (run && run.reason !== v) flush();
          run ??= { reason: v, nodes: [], ids: [], options: [] };
          run.nodes.push(...top.slice(j, end));
          const id = `${hit.key}#${hit.entry.i}`;
          run.ids.push(id);
          run.options.push(gateOptionId(hit.entry, id));
        }
        j = end - 1;
        continue;
      }
    }
    // Card step 13b: a ledger prose gate below the character's level joins the run of folded parts —
    // the whole paragraph, alone (the ledger never lists a paragraph a later block goes on from). Looked
    // up by (page, hash): the record the card opened, else the page the tree's title links to.
    const ph = n.t === 'p' ? paragraphHash(top, j) : undefined;
    const gate = ph ? proseGateAt(ix, ph, [own, (titleRef ??= pageRefOf(top) ?? '')]) : undefined;
    if (gate && proseVerdict(gate.entry, scope) !== 'open') {
      if (run && run.reason !== 'future') flush();
      run ??= { reason: 'future', nodes: [], ids: [], options: [] };
      run.nodes.push(n);
      const id = `${gate.key}#${gate.entry.i}`;
      run.ids.push(id);
      run.options.push(id);
      continue;
    }
    flush();
    const block = blocks.get(j);
    if (block && pick.length) {
      const scoped = scopeChoiceBlock(top, block, pick, own!, treatment);
      if (scoped) {
        out.push(...scoped);
        changed = true;
        j = block.end - 1;
        continue;
      }
    }
    if (ph) {
      const imp = ix.impulses.get(ph);
      if (imp && impulseApplies(imp.entry, scope.level)) {
        const marked: ScopedNode = { ...n, applies: true };
        out.push(marked);
        changed = true;
        continue;
      }
    }
    out.push(n);
  }
  flush();
  return changed ? { ...tree, c: out } : tree;
}

/**
 * A pointer row (champion relentless-reaction@9 "listed in your cause", barbarian raging-resistance):
 * the page key and title of the subclass section it shows, or null. Needs the character's class and
 * subclass; an unknown subclass shows nothing extra (the row's own text stays whole).
 */
export function pointerOf(bucket: string | undefined, id: string, scope: CardScope | undefined, ledger: LevelFoldLedger = LEVEL_FOLDS): { pageKey: string; title: string } | null {
  if (!scope?.subclassId || !bucket) return null;
  const p = ledger.pointers?.[`${bucket}:${id}`];
  if (!p || (scope.classId && scope.classId !== p.classId)) return null;
  const pageKey = ledger.subclassPages?.[`${p.classId}:${scope.subclassId}`];
  return pageKey ? { pageKey, title: p.title } : null;
}

/**
 * Append the subclass section a pointer row shows, from the subclass page's tree, after the row's own
 * page: a `card-pointer` node (print, from that page), folded like any ledger section when the
 * character has not reached its level. Only a section the ledger lists is ever taken.
 */
export function withPointer(tree: AstNode, pageTree: AstNode | undefined, ptr: { pageKey: string; title: string } | null, scope: CardScope | undefined, ledger: LevelFoldLedger = LEVEL_FOLDS, treatment: FutureTreatment = FUTURE_TREATMENT): AstNode {
  if (!ptr || !pageTree || !scope) return tree;
  const ix = indexOf(ledger);
  const top = pageTree.c ?? [];
  for (let j = 0; j < top.length; j++) {
    if (!isLevelTitle(top[j])) continue;
    const hit = ix.sections.get(sectionHash(top, j));
    if (!hit || hit.entry.title !== ptr.title) continue;
    const section: ScopedNode = { t: 'card-pointer', c: top.slice(j, sectionEnd(top, j)), pointerFrom: ptr.pageKey };
    const v = sectionVerdict(hit.entry, scope);
    const id = `${hit.key}#${hit.entry.i}`;
    const add: ScopedNode = v === 'open' ? section : runFold(v, [section], [id], [gateOptionId(hit.entry, id)], treatment);
    return { ...tree, c: [...(tree.c ?? []), add] };
  }
  return tree;
}

/**
 * The scope of a character's own card, read off the stored character (what buildCharacter returns):
 * its level, class and subclass, and the ownership sets build.ts already decided — the implement
 * benefits pushBenefit placed in classChoices (initiate-/adept-/paragon-benefit-<implement>), the
 * kinetic gate's elements (<element>-gate, forks included; one element at level 1 = a single gate) and
 * the inventor's innovation type. A set with nothing on the character stays ABSENT (UNKNOWN ≠ EMPTY).
 * Card step 13c: also the class picks (picks[CLASS_PICKS]) that scope a classFeatures page's choose-one
 * blocks.
 */
export function scopeOfCharacter(ch: Character | null | undefined): CardScope | undefined {
  if (!ch) return undefined;
  const level = Number(ch.level) || 0;
  const scope: CardScope = { level };
  if (ch.classId) scope.classId = ch.classId;
  if (ch.subclassId) scope.subclassId = ch.subclassId;
  const rows = (ch.classChoices ?? []).filter((r) => typeof r.id === 'string' && Number(r.level ?? 0) <= level);
  if (ch.classChoices) scope.owned = rows.map((r) => r.id as string);
  const tierOf = (re: RegExp) => rows.map((r) => re.exec(r.id as string)?.[1]).filter((x): x is string => !!x);
  const owned = tierOf(/^initiate-benefit-(.+)$/);
  if (owned.length) scope.implements = { owned, adept: tierOf(/^adept-benefit-(.+)$/), paragon: tierOf(/^paragon-benefit-(.+)$/) };
  const gates = rows.filter((r) => /^(?:air|earth|fire|metal|water|wood)-gate$/.test(r.id as string));
  if (gates.length) {
    const atOne = gates.filter((r) => Number(r.level ?? 0) <= 1);
    scope.elements = { owned: gates.map((r) => (r.id as string).replace(/-gate$/, '')) };
    if (atOne.length === 1) scope.elements.single = (atOne[0].id as string).replace(/-gate$/, '');
  }
  if (ch.inventor?.innovationType) scope.innovation = ch.inventor.innovationType;
  // Card step 13c: the class picks a classFeatures page's choose-one block may name (CLASS_PICKS) — the
  // subclass row's name ("Fencer": exemplary-finisher's styles) and the divine font (divine-font's
  // Healing / Harmful Font) — and, per page (ELEMENT_PICK_PAGES), the gate's elements. Only what the
  // character stores; nothing stored → no class picks (UNKNOWN ≠ EMPTY: the page stays whole).
  const subclassRows = rows.filter((r) => !!r.id && (r.id === ch.subclassId || r.id === ch.subclassId2));
  const font = (ch.spellcasting ?? []).find((e) => e.font)?.font?.type;
  const classPicks = [
    ...subclassRows.map((r) => r.name),
    ...(font && FONT_LABELS[font] ? [FONT_LABELS[font]] : []),
  ].filter((l) => typeof l === 'string' && l.trim() && !l.includes('\n'));
  const picks: Record<string, string> = {};
  if (classPicks.length) picks[CLASS_PICKS] = [...new Set(classPicks)].join('\n');
  const elementLabel = (e: string) => e.charAt(0).toUpperCase() + e.slice(1);
  for (const [slug, which] of Object.entries(ELEMENT_PICK_PAGES)) {
    const els = which === 'single' ? (scope.elements?.single ? [scope.elements.single] : []) : (scope.elements?.owned ?? []);
    if (els.length) picks[elementPicksKey(slug)] = [...new Set(els.map(elementLabel))].join('\n');
  }
  if (Object.keys(picks).length) scope.picks = picks;
  return scope;
}

